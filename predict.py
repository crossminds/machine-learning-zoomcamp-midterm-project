"""Fraud scoring web service.

Loads the model saved by train.py (models/model.bin) and serves it with FastAPI:

    POST /predict   one transaction -> fraud probability + yes/no decision
    GET  /health    liveness check
    GET  /docs      interactive API docs (generated by FastAPI)

Run locally:
    uv run uvicorn predict:app --host 0.0.0.0 --port 9696
"""

import os
import pickle
from pathlib import Path

import pandas as pd
from fastapi import FastAPI
from pydantic import BaseModel, ConfigDict, Field

from common import RAW_COLUMNS

MODEL_PATH = Path(os.getenv("MODEL_PATH", Path(__file__).resolve().parent / "models" / "model.bin"))

with open(MODEL_PATH, "rb") as f_in:
    artifact = pickle.load(f_in)

model = artifact["pipeline"]
threshold = artifact["threshold"]

