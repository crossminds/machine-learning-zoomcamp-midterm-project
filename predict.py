class Transaction(BaseModel):
    """One card transaction: the raw columns of the dataset (without Class)."""

    model_config = ConfigDict(json_schema_extra={"examples": [EXAMPLE]})

    Time: float = Field(ge=0, description="Seconds since the first transaction in the dataset")
    V1: float
    V2: float
    V3: float
